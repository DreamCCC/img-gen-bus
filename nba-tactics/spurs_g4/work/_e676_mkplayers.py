"""Builds e676w_players.json. BR feet are often hidden by the front row before f218 and after ~f258, so his floor
point is a per-frame manual list: max(SAM box bottom, box top + 195 px) up to f196, hand-read
floor points through the jump, SAM box bottom from f219."""
import json

import numpy as np

br = {int(k): v for k, v in json.load(open("work/e676w/sam_9012.json")).items() if int(k) < 140}
br.update({int(k): v for k, v in json.load(open("work/e676w/sam_9011.json")).items()})
man = {}
for f in range(80, 197):
    b = br[f]
    man[f] = ((b[0] + b[2]) / 2, max(b[3], b[1] + 195))
keys = {196: man[196], 204: (836, 862), 218: (858, 860)}
ks = sorted(keys)
for f in range(197, 219):
    for a, c in zip(ks[:-1], ks[1:]):
        if a <= f <= c:
            t = (f - a) / (c - a)
            man[f] = tuple(np.array(keys[a]) * (1 - t) + np.array(keys[c]) * t)
for f in range(219, 286):
    b = br[f]
    man[f] = ((b[0] + b[2]) / 2, b[3])

players = [
    {"key": "BR", "name": "Brunson", "num": "11", "team": "NYK", "ids": [[9012, 80, 139], [9011, 140, 285]],
     "manual": [[f, round(x, 1), round(y, 1)] for f, (x, y) in sorted(man.items())]},
    {"key": "WB", "name": "Wembanyama", "num": "1", "team": "SAS", "ids": [[9002, 82, 139], [9001, 140, 285]],
     "manual": [[204, 895, 790]], "air": [[204, 228]]},
]
extra = json.load(open("work/_e676_s06_players.json")) if __import__("os").path.exists("work/_e676_s06_players.json") else []
out = {"_note": "e676 (raw/2606111127202702.mp4). 9001 = Wembanyama, 9011 = Brunson: SAM2 video follow "
                "(film/out/s04/_tools/sam_follow.py, seed f175) injected into work/e676w/tracks.json (YOLO original in "
                "tracks_yolo.json). BR manual floor points generated by work/_e676_mkplayers.py (feet hidden by the front row). "
                "WB air 204-228: contest jump, SAM mask merges with Brunson.",
       "players": players + extra}
json.dump(out, open("e676w_players.json", "w"), indent=1)
print(len(man), "BR manual points;", len(extra), "extra players")
