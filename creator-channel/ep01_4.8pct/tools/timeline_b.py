def spoken(ln):
    return ln.get("say", ln["text"])


t = 0.0
vo, marks = [], {}
for ln in LINES:
    lid = ln["id"]
    t += PRE.get(lid, GAP)
    d = DUR[lid]
    s = spoken(ln)
    words = {}
    for w in WORDS.get(lid, []):
        k = s.find(w)
        assert k >= 0, (lid, w)
        words[w] = round(t + d * k / len(s), 3)
    vo.append({"id": lid, "t": round(t, 3), "dur": d, "text": ln["text"], "words": words})
    t += d
    for name, dd in INSERT_AFTER.get(lid, []):
        marks[name] = round(t, 3)
        t += dd
duration = round(t + TAIL, 2)
out = {"duration": duration, "vo": vo, "marks": marks}
(ROOT / "scenes/film_b.json").write_text(json.dumps(out, ensure_ascii=False, indent=1))
print(f"duration {duration:.2f}s ({int(duration // 60)}:{duration % 60:05.2f})")
for v in vo:
    print(f"{v['id']}  {v['t']:7.2f}  {v['dur']:5.2f}  {v['text'][:24]}")
